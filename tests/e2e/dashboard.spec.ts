test('chart controls dismiss with pointer and keyboard and exports contain concise count context', async ({ page }) => {
  await page.goto('/analytics');
  await expect(page.locator('.chart-content canvas').first()).toBeVisible();
  const card = page.getByRole('article', { name: 'Crashes by year', exact: true });
  const info = page.getByLabel('About Crashes by year', { exact: true });
  await info.click(); await expect(card.locator('.chart-help')).toHaveAttribute('open', '');
  await card.locator('h2').click(); await expect(card.locator('.chart-help')).not.toHaveAttribute('open');
  await page.getByRole('button', { name: 'Expand Crashes by year', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Crashes by year', exact: true });
  const close = page.getByRole('button', { name: 'Close expanded Crashes by year', exact: true });
  await expect(dialog).toBeVisible(); await expect(close).toBeFocused();
  await info.click(); await page.keyboard.press('Escape');
  await expect(dialog.locator('.chart-help')).not.toHaveAttribute('open');
  await expect(dialog).toBeVisible();
  await page.screenshot({ path: '.local/qa/chart-expanded.png' });
  await close.click(); await expect(dialog).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Expand Crashes by year', exact: true })).toBeFocused();
  await page.getByRole('button', { name: 'Expand Crashes by year', exact: true }).click();
  await page.locator('.chart-backdrop').click({ position: { x: 10, y: 10 } });
  await expect(dialog).toHaveCount(0);
  await page.evaluate(() => {
    const capture = window as unknown as { exportedText: string[] }; capture.exportedText = [];
    const original = CanvasRenderingContext2D.prototype.fillText;
    CanvasRenderingContext2D.prototype.fillText = function(text, x, y, maxWidth) {
      capture.exportedText.push(text);
      if (maxWidth === undefined) original.call(this, text, x, y); else original.call(this, text, x, y, maxWidth);
    };
  });
  const downloading = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export Crashes by year as PNG' }).click();
  await (await downloading).saveAs('.local/qa/chart-export.png');
  const text = await page.evaluate(() => (window as unknown as { exportedText: string[] }).exportedText.join(' '));
  expect(text).toContain('Crashes by year'); expect(text).toContain('unique crashes');
  expect(text).toContain('Counts describe nearby roads'); expect(text).toContain('2016–2025');
  expect(text).not.toMatch(/UW|GIST|WYDOT|REDISTRIBUTION|LOCAL RESEARCH/);
  await page.screenshot({ path: '.local/qa/analytics-polished.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Expand Crashes by year', exact: true }).click();
  await expect(close).toBeVisible(); await close.click();
  await expect(page.getByRole('button', { name: 'Reset analytics filters' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('link', { name: 'Map', exact: true }).first().click();
  await expect(page.getByRole('button', { name: 'Reset map and filters' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: '.local/qa/map-polished-mobile.png' });
});
